def check_environment():
    if not os.path.exists(RUSH_DEV_DEPS):
        raise FileNotFoundError(f"Rush dev-deps directory not found: {RUSH_DEV_DEPS}")
    d8_jar = os.path.join(RUSH_TOOLS, "other", "d8.jar")
    if not os.path.exists(d8_jar):
        raise FileNotFoundError(f"d8.jar not found: {d8_jar}")

def compile_java():
    print("Compiling Java source files...")
    if os.path.exists(BIN_DIR):
        shutil.rmtree(BIN_DIR)
    os.makedirs(BIN_DIR, exist_ok=True)

    cp = [
        os.path.join(RUSH_DEV_DEPS, "android.jar"),
        os.path.join(RUSH_DEV_DEPS, "rush", "runtime.jar"),
        os.path.join(RUSH_DEV_DEPS, "rush", "annotations.jar"),
        os.path.join(RUSH_DEV_DEPS, "kotlin", "kotlin-stdlib.jar")
    ]
    androidx_dir = os.path.join(RUSH_DEV_DEPS, "androidx")
    if os.path.exists(androidx_dir):
        for f in os.listdir(androidx_dir):
            if f.endswith(".jar"):
                cp.append(os.path.join(androidx_dir, f))

    deps_dir = os.path.join(ADMOB_SRC_DIR, "deps")
    for f in os.listdir(deps_dir):
        if f.endswith(".jar"):
            cp.append(os.path.join(deps_dir, f))

    classpath = ":".join(cp)

    sources = [
        os.path.join(ADMOB_SRC_DIR, "src", "androidx", "browser", "R.java"),
        os.path.join(ADMOB_SRC_DIR, "src", "com", "google", "android", "gms", "ads", "R.java"),
        os.path.join(ADMOB_SRC_DIR, "src", "com", "google", "android", "gms", "common", "R.java"),
        os.path.join(ADMOB_SRC_DIR, "src", "com", "thecodingbus", "admob", "TCBAdMob.java")
    ]

    javac_cmd = ["javac", "-source", "8", "-target", "8", "-cp", classpath, "-d", BIN_DIR] + sources
    res = subprocess.run(javac_cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print("Java compilation failed!\n", res.stderr)
        sys.exit(1)
    print("Java compilation successful.")

def build_aix():
    print("Packaging AIX file...")
    source_aix = AIX_OUT

    with zipfile.ZipFile(source_aix, "r") as aix:
        prefix = "com.thecodingbus.admob/"
        ar_bytes = aix.read(prefix + "files/AndroidRuntime.jar")
        extension_props = aix.read(prefix + "extension.properties")
        comp_json_raw = aix.read(prefix + "components.json").decode("utf-8")
        comp_build_info = aix.read(prefix + "files/component_build_info.json")
        comp_build_infos = aix.read(prefix + "files/component_build_infos.json")
        icon_path = os.path.join(ADMOB_SRC_DIR, "assets", "icon.png")
        if os.path.exists(icon_path):
            with open(icon_path, "rb") as f_icon:
                icon_bytes = f_icon.read()
        else:
            icon_bytes = aix.read(prefix + "aiwebres/icon.png")

    comp_obj = json.loads(comp_json_raw)
    comp_obj[0]["name"] = "TCBAdMob"
    comp_obj[0]["type"] = "com.thecodingbus.admob.TCBAdMob"
    comp_obj[0]["helpDescription"] = "Google AdMob extension for MIT App Inventor."
    comp_obj[0]["helpString"] = "<p><b>TCBAdMob Extension</b><br>Google AdMob integration for MIT App Inventor.<br><br><b>Developer:</b> The Coding Bus<br><b>Website:</b> <a href=\"https://thecodingbus.info\" target=\"_blank\">thecodingbus.info</a></p>"
    comp_obj[0]["helpUrl"] = "https://thecodingbus.info"
    comp_obj[0]["version"] = "1"
    comp_obj[0]["versionName"] = "1.0.0"

    methods = comp_obj[0].get("methods", [])
    if not any(m.get("name") == "ShowBannerAd" for m in methods):
        methods.insert(3, {
            "deprecated": "false",
            "name": "ShowBannerAd",
            "description": "Displays the loaded banner ad in the container.",
            "params": []
        })
    comp_obj[0]["methods"] = methods

    for p in comp_obj[0].get("properties", []):
        if p.get("name") == "FallbackToTestAds":
            p["defaultValue"] = "True"
        elif p.get("name") == "TestMode":
            p["defaultValue"] = "True"
        elif p.get("name") == "ShowDebugToasts":
            p["defaultValue"] = "False"
        elif p.get("name") == "AppId":
            p["defaultValue"] = "ca-app-pub-3940256099942544~3347511713"
        elif p.get("name") == "AdUnitId":
            p["defaultValue"] = "ca-app-pub-3940256099942544/6300978111"

    updated_comp_json = json.dumps(comp_obj, separators=(',', ':')).encode("utf-8")

    # Standardize component build info with official test App ID
    comp_bi_obj = json.loads(comp_build_info)
    for c in comp_bi_obj:
        c["type"] = "com.thecodingbus.admob.TCBAdMob"
        if "metadata" in c:
            c["metadata"] = [
                re.sub(r'ca-app-pub-[0-9~]+', 'ca-app-pub-3940256099942544~3347511713', m)
                for m in c["metadata"]
            ]
        if "activities" in c:
            c["activities"] = [
                re.sub(r'ca-app-pub-[0-9~]+', 'ca-app-pub-3940256099942544~3347511713', a)
                for a in c["activities"]
            ]
    updated_comp_bi = json.dumps(comp_bi_obj, separators=(',', ':')).encode("utf-8")

    new_classes = {}
    for root, _, files in os.walk(BIN_DIR):
        for f in files:
            full_path = os.path.join(root, f)
            arcname = os.path.relpath(full_path, BIN_DIR)
            with open(full_path, "rb") as cf:
                new_classes[arcname] = cf.read()

    temp_ar_path = os.path.join(BASE_DIR, "temp_AndroidRuntime.jar")
    with zipfile.ZipFile(io.BytesIO(ar_bytes), "r") as zin:
        with zipfile.ZipFile(temp_ar_path, "w", compression=zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                if item.filename in new_classes:
                    zout.writestr(item.filename, new_classes.pop(item.filename))
                elif not item.filename.startswith("com/example/"):
                    zout.writestr(item, zin.read(item.filename))
            for name, data in new_classes.items():
                zout.writestr(name, data)

    temp_classes_jar = os.path.join(BASE_DIR, "temp_classes.jar")
    if os.path.exists(temp_classes_jar):
        os.remove(temp_classes_jar)

    d8_jar = os.path.join(RUSH_TOOLS, "other", "d8.jar")
    android_jar = os.path.join(RUSH_DEV_DEPS, "android.jar")
    d8_cmd = [
        "java", "-cp", d8_jar,
        "com.android.tools.r8.D8",
        "--output", temp_classes_jar,
        temp_ar_path,
        "--lib", android_jar,
        "--min-api", "14"
    ]
    res = subprocess.run(d8_cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print("d8 failed!\n", res.stderr)
        sys.exit(1)

    with open(temp_ar_path, "rb") as f:
        new_ar_bytes = f.read()
    with open(temp_classes_jar, "rb") as f:
        new_cj_bytes = f.read()

    if os.path.exists(temp_ar_path):
        os.remove(temp_ar_path)
    if os.path.exists(temp_classes_jar):
        os.remove(temp_classes_jar)

    with zipfile.ZipFile(AIX_OUT, "w", compression=zipfile.ZIP_DEFLATED) as zout:
        zout.writestr("com.thecodingbus.admob/classes.jar", new_cj_bytes)
        zout.writestr("com.thecodingbus.admob/extension.properties", extension_props)
        zout.writestr("com.thecodingbus.admob/components.json", updated_comp_json)
        zout.writestr("com.thecodingbus.admob/files/component_build_info.json", updated_comp_bi)
        zout.writestr("com.thecodingbus.admob/files/component_build_infos.json", updated_comp_bi)
        zout.writestr("com.thecodingbus.admob/files/AndroidRuntime.jar", new_ar_bytes)
        zout.writestr("com.thecodingbus.admob/aiwebres/icon.png", icon_bytes)

    if os.path.exists(BIN_DIR):
        shutil.rmtree(BIN_DIR)

    print(f"Build complete: {AIX_OUT} ({os.path.getsize(AIX_OUT):,} bytes)")

